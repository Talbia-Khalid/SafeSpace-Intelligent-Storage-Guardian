
#include <stdio.h>
#include <stdlib.h>
#include <dirent.h>
#include <sys/stat.h>
#include <sys/statvfs.h>
#include <unistd.h>
#include <string.h>
#include <time.h>

void get_folder_info(char path[], unsigned long long *size, int *count)
{
    DIR *dir = opendir(path);

    if (dir == NULL)
        return;

    struct dirent *entry;

    while ((entry = readdir(dir)) != NULL)
    {
        if (strcmp(entry->d_name, ".") == 0 ||
            strcmp(entry->d_name, "..") == 0)
            continue;

        char full_path[1024];

        snprintf(full_path, sizeof(full_path),
                 "%s/%s", path, entry->d_name);

        struct stat file_info;

        if (lstat(full_path, &file_info) == 0)
        {
            if (S_ISDIR(file_info.st_mode))
            {
                get_folder_info(full_path, size, count);
            }
            else if (S_ISREG(file_info.st_mode))
            {
                *size += file_info.st_size;
                (*count)++;
            }
        }
    }

    closedir(dir);
}

void generate_storage_report(char path[])
{
    unsigned long long folder_size = 0;
    int file_count = 0;

    get_folder_info(path, &folder_size, &file_count);

    struct statvfs disk_info;

    if (statvfs("/", &disk_info) != 0)
    {
        printf("Unable to read system storage information.\n");
        return;
    }

    unsigned long long total =
        (unsigned long long)disk_info.f_blocks * disk_info.f_frsize;

    unsigned long long available =
        (unsigned long long)disk_info.f_bavail * disk_info.f_frsize;

    unsigned long long used = total - available;

    double percentage = 0;

    if (total > 0)
        percentage = ((double)used / total) * 100;

    time_t current_time = time(NULL);
    struct tm *time_info = localtime(&current_time);

    char date_time[100];

    strftime(date_time, sizeof(date_time),
             "%d-%m-%Y %H:%M:%S", time_info);

    char report_name[256];

    snprintf(report_name, sizeof(report_name),
             "reports/safespace_report_%ld.txt",
             (long)current_time);

    FILE *report = fopen(report_name, "w");

    if (report == NULL)
    {
        printf("Unable to create report.\n");
        return;
    }

    fprintf(report, "====================================\n");
    fprintf(report, "       SAFESPACE STORAGE REPORT\n");
    fprintf(report, "====================================\n\n");

    fprintf(report, "Report Date: %s\n", date_time);
    fprintf(report, "Selected Folder: %s\n\n", path);

    fprintf(report, "--------- FOLDER ANALYSIS ---------\n");
    fprintf(report, "Total Files: %d\n", file_count);
    fprintf(report, "Folder Size: %.2f MB\n",
            (double)folder_size / (1024 * 1024));

    fprintf(report, "\n--------- SYSTEM STORAGE ---------\n");
    fprintf(report, "Total Storage: %.2f GB\n",
            (double)total / (1024 * 1024 * 1024));

    fprintf(report, "Used Storage: %.2f GB\n",
            (double)used / (1024 * 1024 * 1024));

    fprintf(report, "Available Storage: %.2f GB\n",
            (double)available / (1024 * 1024 * 1024));

    fprintf(report, "Storage Usage: %.2f%%\n", percentage);

    fprintf(report, "\n====================================\n");
    fprintf(report, "Report generated by SafeSpace.\n");
    fprintf(report, "====================================\n");

    fclose(report);

    printf("\nStorage report created successfully!\n");
    printf("Report saved at: %s\n", report_name);
}

